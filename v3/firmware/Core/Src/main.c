void audio_start(void)
{
    memset(i2s_dma_buf, 0, sizeof i2s_dma_buf);   // start with silence
    HAL_I2S_Transmit_DMA(&hi2s2, (uint16_t *)i2s_dma_buf, 2 * SAMPLES_PER_HALF);
}

void audio_task(void) {

	for (int half = 0; half < 2; half++) {

        if (half_needs_fill[half]) {

            half_needs_fill[half] = false;

            fillHalfBuffer(half);

        }

    }

}

static void fillHalfBuffer(int half)
{
    int32_t *dest = &i2s_dma_buf[half * SAMPLES_PER_HALF];
    uint16_t got = tud_audio_read(usb_audio_buf, USB_BYTES_PER_HALF);

    // Only use whole stereo frames (6 bytes each)
    uint16_t samples = got / USB_BYTES_PER_SAMPLE;
    samples &= ~1u;

    for (uint16_t i = 0; i < samples; i++)
    {
        // Real signed 24-bit value, left-aligned in 32 bits
        int32_t sample = usb24_to_i2s32(&usb_audio_buf[i * USB_BYTES_PER_SAMPLE]);

        // Volume on the real value
        sample = (int32_t)((float)sample * gain);

        // Swap halfwords last, in the order the I2S peripheral sends them
        dest[i] = (int32_t)swap_halfwords((uint32_t)sample);
    }

    // pad the rest with silence (zero is the same after the swap)
    if (samples < SAMPLES_PER_HALF)
    {
        memset(&dest[samples], 0, (SAMPLES_PER_HALF - samples) * sizeof(int32_t));
    }
}

static void update_gain(void) {

	if(mute[0]) {
		gain = 0.0f;
	} else {
		gain = powf(10.0f, volume[0] / 20.0f);
	}
}

static void reconfigure_i2s(uint32_t newSampleRate) {
    HAL_I2S_DMAStop(&hi2s2);
    HAL_I2S_DeInit(&hi2s2);

    hi2s2.Init.AudioFreq = newSampleRate;
    if (HAL_I2S_Init(&hi2s2) != HAL_OK) {
        Error_Handler();
    }

    half_needs_fill[0] = false;
    half_needs_fill[1] = false;
    audio_start();
}

static uint32_t swap_halfwords(uint32_t value) {

	return (value << 16) | (value >> 16);
}

static int32_t usb24_to_int32(const uint8_t *p)
{
    // USB sends 24-bit samples LSB first
    // 24 bits of a 32-bit word keeps the sign bit in the right place.
    uint32_t raw = ((uint32_t)p[0] << 8) |
                   ((uint32_t)p[1] << 16) |
                   ((uint32_t)p[2] << 24);

    return (int32_t)raw;
}

